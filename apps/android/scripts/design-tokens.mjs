import { readFile, writeFile } from 'node:fs/promises';
import ts from '../../web/node_modules/typescript/lib/typescript.js';

// Android and the browser consume the same semantic palette. Do not hand-copy colors.
const source = await readFile(new URL('../../web/src/ui/theme/tokens.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const { COLORS, AVATAR_COLORS } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const color = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const roles = Object.keys(COLORS.light).filter((key) => COLORS.light[key].startsWith('#'));
const output = `// Generated by scripts/design-tokens.mjs from apps/web/src/ui/theme/tokens.ts.
package com.convo.android.ui.theme

import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.graphics.Color

data class ConvoColors(\n${roles.map((key) => `    val ${key}: Color,`).join('\n')}\n)
${['light', 'dark'].map((mode) => `val ${mode === 'light' ? 'Light' : 'Dark'}ConvoColors = ConvoColors(\n${roles.map((key) => `    ${key} = ${color(COLORS[mode][key])},`).join('\n')}\n)`).join('\n')}
val LocalConvoColors = staticCompositionLocalOf { LightConvoColors }
val AvatarColors = listOf(${AVATAR_COLORS.map(color).join(', ')})
`;
await writeFile(new URL('../app/src/main/java/com/convo/android/ui/theme/DesignTokens.kt', import.meta.url), output);
