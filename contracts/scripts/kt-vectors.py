#!/usr/bin/env python3
"""Generates contracts/vectors/kt-v1.json: key-transparency encodings and RFC 9162 Merkle proofs,
computed independently of the Java server and the TypeScript client (both assert this file)."""
import base64, hashlib, json, struct, uuid, os

def b64(b): return base64.urlsafe_b64encode(b).rstrip(b'=').decode()
def sha(*parts): h = hashlib.sha256(); [h.update(p) for p in parts]; return h.digest()
def leaf_hash(leaf): return sha(b'\x00', leaf)
def node(l, r): return sha(b'\x01', l, r)
def split(n):
    k = 1
    while k * 2 < n: k *= 2
    return k
def mth(ls):
    if len(ls) == 0: return sha()
    if len(ls) == 1: return ls[0]
    k = split(len(ls)); return node(mth(ls[:k]), mth(ls[k:]))
def path(m, ls):
    if len(ls) <= 1: return []
    k = split(len(ls))
    return path(m, ls[:k]) + [mth(ls[k:])] if m < k else path(m - k, ls[k:]) + [mth(ls[:k])]
def subproof(m, ls, b):
    n = len(ls)
    if m == n: return [] if b else [mth(ls)]
    k = split(n)
    return subproof(m, ls[:k], b) + [mth(ls[k:])] if m <= k else subproof(m - k, ls[k:], False) + [mth(ls[:k])]

def device_hash(devices):
    data = b'CONVO-KT-DEVICES-V1\n' + b''.join(struct.pack('>II', d, r) for d, r in sorted(devices))
    return sha(data)
def leaf(account, version, ik, dh):
    return b'CONVO-KT-LEAF-V1\n' + uuid.UUID(account).bytes + struct.pack('>QH', version, len(ik)) + ik + dh
def cosigned(head_bytes, ts): return b'CONVO-KT-COSIGN-V1\n' + struct.pack('>Q', ts) + head_bytes
def head(dep, size, root, ts): return ('CONVO-KT-HEAD-V1\n' + dep + '\n').encode() + struct.pack('>Q', size) + root + struct.pack('>Q', ts)

accounts = ['0b5e2c1a-7d3f-4e6a-9b8c-%012x' % i for i in range(1, 8)]
entries, leaves = [], []
for i, acc in enumerate(accounts):
    ik = bytes([5]) + sha(acc.encode())  # 33-byte Signal-style key (0x05 prefix)
    devices = [(d, 1000 + 7 * d + i) for d in range(1, 2 + i % 3)][::-1]  # unsorted on purpose
    dh = device_hash(devices); lb = leaf(acc, i + 1, ik, dh)
    entries.append({'accountId': acc, 'identityKey': b64(ik), 'deviceListVersion': i + 1,
                    'devices': [{'deviceId': d, 'registrationId': r} for d, r in devices],
                    'deviceHash': b64(dh), 'leaf': b64(lb), 'leafHash': b64(leaf_hash(lb))})
    leaves.append(leaf_hash(lb))
roots = {str(n): b64(mth(leaves[:n])) for n in range(0, len(leaves) + 1)}
inclusion = [{'index': m, 'size': n, 'path': [b64(x) for x in path(m, leaves[:n])]} for n in range(1, len(leaves) + 1) for m in range(n)]
consistency = [{'from': m, 'to': n, 'proof': [b64(x) for x in subproof(m, leaves[:n], True)]} for n in range(1, len(leaves) + 1) for m in range(1, n + 1)]
out = {'description': 'Key transparency CONVO-KT-*-V1 encodings and RFC 9162 Merkle proofs (generated by contracts/scripts/kt-vectors.py).',
       'entries': entries, 'roots': roots, 'inclusion': inclusion, 'consistency': consistency,
       'head': {'deploymentId': 'convo-test', 'size': 7, 'root': roots['7'], 'timestamp': 1761400000000,
                'bytes': b64(head('convo-test', 7, mth(leaves), 1761400000000)),
                'cosignTimestamp': 1761403600000,
                'cosignBytes': b64(cosigned(head('convo-test', 7, mth(leaves), 1761400000000), 1761403600000))}}
path_out = os.path.join(os.path.dirname(__file__), '..', 'vectors', 'kt-v1.json')
with open(path_out, 'w') as f: json.dump(out, f, indent=2); f.write('\n')
print('wrote', os.path.normpath(path_out))

# --- verifiable map (sparse Merkle tree, CONVO-KT-MAPKEY-V1) ---------------------------------------
DEPTH = 256
EMPTY = [bytes(32)]
for _ in range(DEPTH): EMPTY.append(sha(b'\x01', EMPTY[-1], EMPTY[-1]))
def map_key(account): return sha(b'CONVO-KT-MAPKEY-V1\n', uuid.UUID(account).bytes)
def bit(key, d): return (key[d // 8] >> (7 - d % 8)) & 1
def smt(entries, depth):  # entries: sorted list of (key, value)
    if not entries: return EMPTY[DEPTH - depth]
    if depth == DEPTH: return sha(b'\x02', entries[0][0], entries[0][1])
    left = [e for e in entries if not bit(e[0], depth)]; right = [e for e in entries if bit(e[0], depth)]
    if len(entries) == 1:
        k, v = entries[0]; h = sha(b'\x02', k, v)
        for d in range(DEPTH - 1, depth - 1, -1): h = sha(b'\x01', EMPTY[DEPTH - d - 1], h) if bit(k, d) else sha(b'\x01', h, EMPTY[DEPTH - d - 1])
        return h
    return sha(b'\x01', smt(left, depth + 1), smt(right, depth + 1))
def smt_proof(entries, key):
    bitmap = bytearray(32); sibs = []; cur = entries
    for d in range(DEPTH):
        left = [e for e in cur if not bit(e[0], d)]; right = [e for e in cur if bit(e[0], d)]
        sib = smt(left, d + 1) if bit(key, d) else smt(right, d + 1)
        if sib != EMPTY[DEPTH - d - 1]: bitmap[d // 8] |= 0x80 >> (d % 8); sibs.append(sib)
        cur = right if bit(key, d) else left
        if not cur: break
    return bytes(bitmap), sibs

# The map after all 7 leaves; account 3 is updated by an extra leaf so "newest" matters.
latest = {}
for e in entries: latest[e['accountId']] = e['leafHash']
newer = sha(b'newer leaf for account 3')
latest[entries[3]['accountId']] = b64(newer)
items = sorted((map_key(a), base64.urlsafe_b64decode(v + '=' * (-len(v) % 4))) for a, v in latest.items())
absent = '0b5e2c1a-7d3f-4e6a-9b8c-0000000000ff'
proofs = []
for account in [e['accountId'] for e in entries] + [absent]:
    bm, sibs = smt_proof(items, map_key(account))
    proofs.append({'accountId': account, 'key': b64(map_key(account)), 'value': latest.get(account), 'bitmap': b64(bm), 'siblings': [b64(s) for s in sibs]})
map_out = {'description': 'Key transparency verifiable map (sparse Merkle tree) vectors (generated by contracts/scripts/kt-vectors.py).',
           'emptyRoot': b64(EMPTY[DEPTH]), 'root': b64(smt(items, 0)), 'entries': [{'key': b64(k), 'value': b64(v)} for k, v in items], 'proofs': proofs,
           'twoEntryRoot': b64(smt(items[:2], 0))}
with open(os.path.join(os.path.dirname(__file__), '..', 'vectors', 'kt-map-v1.json'), 'w') as f: json.dump(map_out, f, indent=2); f.write('\n')
print('wrote kt-map-v1.json')
